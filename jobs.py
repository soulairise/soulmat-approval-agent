def 멈출까(업무, 건, 판정, 켠관문=None):
    """관문을 돌려 멈출 사유 목록을 만든다. 비어 있으면 자동으로 나간다."""
    사유 = []
    for 이름, fn in JOBS[업무]["관문"]:
        if 켠관문 is not None and 이름 not in 켠관문:
            continue
        r = fn(건, 판정)
        if r:
            사유.append({"관문": 이름, "사유": r})
    return 사유
