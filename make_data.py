라벨프롬프트 = """너는 요가 경전 데이터의 최종 검수자다. 아래는 기계가 낸 번역 수정안이다.
각 수정안에 대해, **사람이 반드시 확인해야 하는지**를 판정하라.

판정 기준은 하나다 — **이 수정이 그대로 반영되면 수련자가 읽는 뜻이 달라지는가.**
오탈자·띄어쓰기·군더더기 정리처럼 뜻이 그대로면 '아니오'.
용어가 바뀌거나, 문장의 주체·대상·논리가 달라지거나, 확신이 안 서면 '예'.

{항목}

JSON 배열만 출력하라.
[{{"ref":"I.2","사람이_봐야하나":true,"이유":"한 줄"}}]"""


def _json(s):
    import re
    m = re.search(r"\[.*\]", s, re.S)
    return json.loads(m.group(0)) if m else []


def 경전(n_verses=120, batch=12):
    """LLM 이 실제로 수정을 제안하게 한다. 그중 나온 것만 처리 대상이 된다."""
    원본 = jload("_경전원본.json")
    r = random.Random(33)
    표본 = r.sample(원본, min(n_verses, len(원본)))
    by_ref = {v["경전"] + " " + v["ref"]: v for v in 원본}

    제안 = []
    for i in range(0, len(표본), batch):
        덩이 = 표본[i:i + batch]
        절들 = "\n".join(f'- {v["ref"]} ({v["경전"]}): {v["ko"]}' for v in 덩이)
        try:
            for p in _json(ask(제안프롬프트.format(절들=절들))):
                본 = next((v for v in 덩이 if v["ref"] == p.get("ref")), None)
                if 본 and p.get("새ko") and p["새ko"].strip() != 본["ko"].strip():
                    제안.append({**p, "경전": 본["경전"], "옛ko": 본["ko"],
                                 "dev": 본["dev"], "iast": 본["iast"], "star": 본["star"]})
        except Exception as e:
            print(f"  ! 덩이 {i//batch+1} 실패: {type(e).__name__}")
        print(f"  {i//batch+1}/{-(-len(표본)//batch)} 덩이 · 누적 제안 {len(제안)}건", flush=True)

    # 라벨 — 판정 모델과 다른 모델이 붙인다
    라벨 = {}
    for i in range(0, len(제안), 15):
        덩이 = 제안[i:i + 15]
        항목 = "\n".join(
            f'- {p["ref"]}: 「{p["옛ko"]}」 → 「{p["새ko"]}」 (종류 {p.get("종류")})'
            for p in 덩이)
        try:
            for x in _json(ask(라벨프롬프트.format(항목=항목), model=LABEL_MODEL)):
                라벨[x.get("ref")] = x
        except Exception as e:
            print(f"  ! 라벨 실패: {type(e).__name__}")

    건 = []
    for i, p in enumerate(제안):
        lb = 라벨.get(p["ref"], {})
        건.append({
            "id": f"S{i+1:02d}", "업무": "경전",
            "경전": p["경전"], "ref": p["ref"], "star": p["star"],
            "옛ko": p["옛ko"], "새ko": p["새ko"], "dev": p["dev"], "iast": p["iast"],
            "종류": p.get("종류", ""), "제안이유": p.get("이유", ""),
            "사람이_봐야하나": bool(lb.get("사람이_봐야하나", True)),
            "_라벨근거": [lb.get("이유", "라벨 실패 — 안전하게 '봐야 함'으로 둔다")],
        })
    return 건


만드는법 = {"견적": 견적, "행사": 행사, "문의": 문의, "경전": 경전}

