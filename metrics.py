# -*- coding: utf-8 -*-
"""멈춤 기준을 재는 세 값.  `python metrics.py` (자체 검증)

교안 3강 그대로다.

  개입률  전체 중 사람에게 온 비율
  놓침    사람이 봤어야 하는데 자동으로 나간 건. **가장 비싼 실수.**
          사람에게 온 목록에 안 뜨므로 따로 세지 않으면 놓쳤다는 사실조차 모른다.
  헛멈춤  볼 필요가 없는데 사람에게 온 건. 많으면 담당자가 내용을 안 보고 승인만 누른다.

`사람이_봐야하나` 라벨이 있어야 놓침·헛멈춤을 셀 수 있다. 이 라벨은 **기준을 재는 데만**
쓰고 에이전트에게는 보여 주지 않는다.
"""
from jobs import 멈출까


def 재기(업무, 건들, 켠관문=None, 판정=None):
    판정 = 판정 or {"결정": "-", "근거": "-", "근거규정": "-", "답변": ""}
    n = len(건들)
    멈춘, 놓침, 헛멈춤 = 0, 0, 0
    놓친목록, 헛멈춘목록 = [], []
    for 건 in 건들:
        사유 = 멈출까(업무, 건, 판정, 켠관문)
        봐야 = 건["사람이_봐야하나"]
        if 사유:
            멈춘 += 1
            if not 봐야:
                헛멈춤 += 1
                헛멈춘목록.append((건["id"], [x["관문"] for x in 사유]))
        elif 봐야:
            놓침 += 1
            놓친목록.append((건["id"], 건["_라벨근거"][0][:40]))
    return {"n": n, "멈춘": 멈춘, "개입률": 멈춘 / n if n else 0,
            "놓침": 놓침, "헛멈춤": 헛멈춤,
            "_놓친목록": 놓친목록, "_헛멈춘목록": 헛멈춘목록}


def 줄(라벨, m, 폭=18):
    return (f"{라벨:<{폭}} 개입률 {m['개입률']:>5.0%} ({m['멈춘']:>2}/{m['n']:>2}) · "
            f"놓침 {m['놓침']:>2} · 헛멈춤 {m['헛멈춤']:>2}")


def self_test():
    건 = [{"id": "a", "사람이_봐야하나": True, "_라벨근거": ["x"],
           "합계": 2_000_000, "단가": 5000, "표준단가": 5000, "신규거래처": False},
          {"id": "b", "사람이_봐야하나": False, "_라벨근거": ["x"],
           "합계": 10_000, "단가": 5000, "표준단가": 5000, "신규거래처": False}]
    m = 재기("견적", 건)
    assert m == {**m, "멈춘": 1, "놓침": 0, "헛멈춤": 0}, m
    m2 = 재기("견적", 건, 켠관문=[])          # 기준 없음
    assert m2["멈춘"] == 0 and m2["놓침"] == 1, m2
    return True


if __name__ == "__main__":
    print("자체 검증:", "통과" if self_test() else "실패")
